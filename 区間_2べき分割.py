"""
# 区間_2べき分割 （セグメント的に分割する）

## 説明
与えられた区間を、セグメント木のノードに対応する区間のうち、できるだけ大きなものを使って分割する。
* 0-index
* 区間の表現は閉区間 [L, R] を表す

例：
divide(0, 16) -> [(0, 15), (16, 16)]
divide(1, 5) -> [(1, 1), (2, 3), (4, 5)]
divide(3, 13) -> [(3, 3), (4, 7), (8, 11), (12, 13)]
divide(99, 131) -> [(99, 99), (100, 103), (104, 111), (112, 127), (128, 131)]

最後の例を使って分け方のルールを解説する。
できるだけ大きなセグメント区間でまとめる。
[64, 127]が区間になるが、そこには入らない。
なのでその右半分 [96, 127] を見る。しかしこれもダメ。
次の右半分 [112, 127] をまとめる。外にある [128, 131] もまとめておく。
[96, 111] の中点 104 で分けるので [104, 111] ができる。
同様に、[99, 99], [100, 103] となる。
この処理を左から順にやっていくのがこのライブラリ。


## 計算量
O( log(R+2)**2 ) らしい。

## 使われる問題
ABC349-D
ABC355-E

## 仕組み
範囲 [L, R] について、L から始まる区間の長さは最大値が決まっている。
L が 2 の何乗の倍数かによって決まる。

* 99 は奇数なので長さ1
* 100 は 2, 4 の倍数だが 8 の倍数ではないので長さ 4
* 102 は 2 の倍数だが 4 の倍数ではないので長さ 2

この仕組みを利用して長さを決める。
そして、R の値によってどの長さ（2の何乗）まで伸ばせるかが決まる。

####################################################
# ライブラリ
"""

import sys
sys.setrecursionlimit(10**7)

def divide(l, r):
  #print(f"divide({l}, {r})")
  if l > r:
    return []
  if l == r:
    return [(l, r)]
  
  # l から始めてどこまでで区切れるか、位置を探す
  # * 2 の乗数で割り切れなくなるまでチェックし、それを加えた分 - 1 が右端 new_r となる
  # * new_r <= r という条件もある
  size = -1
  new_r = l
  while True:
    size += 1
    if l % (2 ** size) != 0:
      break
    next_new_r = l + 2 ** size - 1
    if next_new_r > r:
      break
    new_r = next_new_r

  return [(l, new_r)] + divide(new_r+1, r)

print(divide(0, 16))
print(divide(1, 5))
print(divide(3, 13))
print(divide(52, 64))
print(divide(99, 131))


